class _Parser(argparse.ArgumentParser):
    def error(self, message: str) -> None:  # shaped like every other refusal
        self.exit(2, f"error: {message}\nfix: python3 {SCRIPT_REL} [--check | --contrast | --migrate | --css-vars | --overrides [--apply]] [--root SKILL_DIR] [--project PATH]\n")


def _write(path: Path, text: str, root: Path) -> bool:
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    except OSError as exc:
        print(f"error: cannot write {rel(path, root)} ({exc})\nfix: check the folder exists and is writable", file=sys.stderr)
        return False
    return True


def main(argv: Optional[List[str]] = None) -> int:
    P.utf8_stdio()
    parser = _Parser(prog="build-tokens.py", description="Build the token outputs from the tokens JSON.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when any output is stale or missing")
    parser.add_argument("--contrast", action="store_true", help="rewrite the contrast block of references/dark-mode.md")
    parser.add_argument("--migrate", action="store_true", help="add the missing settings to the tokens JSON (additive)")
    parser.add_argument("--css-vars", action="store_true", help="print the tokens as plain CSS custom properties")
    parser.add_argument("--overrides", action="store_true",
                        help="print, as JSON, the variables a web copy sets in the tokens' namespaces outside Plumb's "
                             "block, each with the token it maps onto and the edits that move it there")
    parser.add_argument("--apply", action="store_true",
                        help="with --overrides: make those edits (the tokens file and the copies); only after the "
                             "user's OK")
    parser.add_argument("--root", metavar="SKILL_DIR", help="the design-system skill folder (default: this script's skill)")
    parser.add_argument("--project", metavar="PATH", help="project root when no PLUMB.md is found above the skill")
    args = parser.parse_args(argv)
    if sum(bool(x) for x in (args.check, args.contrast, args.migrate, args.css_vars, args.overrides)) > 1:
        parser.error("pass only one of --check, --contrast, --migrate, --css-vars, --overrides")
    if args.apply and not args.overrides:
        print(f"error: --apply goes with --overrides\nfix: python3 {SCRIPT_REL} --overrides (show the plan to the "
              f"user), then, only after their OK, python3 {SCRIPT_REL} --overrides --apply", file=sys.stderr)
        return 2
    skill_dir = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[1]
    project = Path(args.project) if args.project else None
    try:
        return _run(args, skill_dir, project)
    except PlumbError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    except (KeyError, TypeError, ValueError, AttributeError, IndexError) as exc:
        print(
            f"error: unexpected token structure ({type(exc).__name__}: {exc})\n"
            f"fix: open the tokens file and compare it with reference/tokens-format.md",
            file=sys.stderr,
        )
        return 2


def print_first_block(path: Path, new: str, root: Path) -> None:
    """For --check: the exact change the build would make to a stylesheet that gets Plumb's block for the first time,
    as a unified diff, so it can be shown to the person and agreed before anything is written."""
    shown = rel(path, root)
    try:
        old = path.read_bytes().decode("utf-8", errors="replace")
    except OSError:
        old = ""
    print(f"would add Plumb's block to {shown} (first time; every other line stays as it is). The change:")
    diff = difflib.unified_diff(P.normalise_text(old).splitlines(), P.normalise_text(new).splitlines(),
                                f"a/{shown}", f"b/{shown}", lineterm="")
    for line in diff:
        print(line)


def template_notes(doc: dict, skill_dir: Path, missing: bool = True) -> List[str]:
    """A note when the tokens set theme_switch or motion.reduced but the project's web template predates the
    {{@dark}} / {{@reduced-motion}} directives, so the setting has no effect yet; and (missing) when the template has
    the directive but the tokens do not say, so the default (both / none) applies without a recorded choice."""
    settings = P.plumb_settings(doc)
    try:
        template = read_template(skill_dir, settings["web"]["styling"])
    except PlumbError:
        return []
    motion = settings.get("motion") if isinstance(settings.get("motion"), dict) else {}
    out = []
    for key, directive, given in (("web.theme_switch", "dark", "theme_switch" in settings["web"]),
                                  ("motion.reduced", "reduced-motion", "reduced" in motion)):
        has = f"{{{{@{directive}}}}}" in template
        if given and not has:
            out.append(f"note: $extensions.plumb.{key} is set, but assets/platforms/web/{TEMPLATE_NAME} has no "
                       f"{{{{@{directive}}}}} line, so it has no effect; /plumb:upgrade offers the current template "
                       f"(or copy {TEMPLATE_NAME}.{settings['web']['styling']} from the Plumb plugin's "
                       f"assets/skill/assets/platforms/web/)")
        elif missing and has and not given:
            default, choices = MISSING_DEFAULTS[key]
            command = f"python3 {rel(skill_dir / SCRIPT_REL, find_project_root(skill_dir))} --migrate"
            out.append(f"note: $extensions.plumb.{key} is not set, so the default {default} applies; keep it with "
                       f"`{command}` (records the defaults, changes nothing else), or record another choice "
                       f"({choices}) with /plumb:update")
    return out


def _load_audit():
    """audit.py from this script's folder (its palette-class scan), or None."""
    import importlib.util
    path = Path(__file__).resolve().parent / "audit.py"
    if not path.is_file():
        return None
    try:
        spec = importlib.util.spec_from_file_location("plumb_audit_for_tokens", path)
        mod = importlib.util.module_from_spec(spec)
        sys.modules["plumb_audit_for_tokens"] = mod
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
        return mod
    except Exception:  # noqa: BLE001 - the warning is a convenience
        return None


def palette_warning(doc: dict, skill_dir: Path, root: Path, tokens_file: Path) -> Optional[str]:
    """When web.reset_palette is true (Tailwind v4, with a web copy in the app) and the app's UI files still use
    Tailwind's default palette classes, a warning with their count: those classes lose their colour once the block
    is in the app. None otherwise (or when the scan cannot run)."""
    web = P.plumb_settings(doc)["web"]
    if web.get("styling") != "tailwind-v4" or not web.get("copies") or not reset_palette(doc):
        return None
    audit = _load_audit()
    if audit is None:
        return None
    try:
        count, files, examples = audit.palette_uses(root, skill_dir, doc)
    except Exception:  # noqa: BLE001
        return None
    if not count:
        return None
    shown = ", ".join(examples) + (", ..." if count > len(examples) else "")
    return (f"warning: web.reset_palette is true, so Plumb's block switches off Tailwind's default palette (and its "
            f"default radii, shadows, text sizes, fonts and easings); {count} palette class"
            f"{'es' if count != 1 else ''} in {len(files)} UI file{'s' if len(files) != 1 else ''} would lose their "
            f"colour ({shown})\n"
            f"fix: ask the user: keep Tailwind's defaults until the app is migrated (set \"reset_palette\": false in "
            f"$extensions.plumb.web of {rel(tokens_file, root)}, then rebuild; the audit then suggests each move), or "
            f"move those classes to colour tokens first (audit.py lists them as palette-colour)")


MISSING_DEFAULTS = {
    "web.theme_switch": ('"both" (dark from the system setting and from the .dark class)',
                         '"both", "system", "class" or "data-theme"'),
    "motion.reduced": ('"none" (no animation or transition when the user asks for less motion)', '"none" or "keep-fades"'),
}


def _run(args: argparse.Namespace, skill_dir: Path, project: Optional[Path]) -> int:
    root = find_project_root(skill_dir, project)
    tokens_file = find_tokens_file(skill_dir)
    doc = P.load_tokens(tokens_file)
    if args.css_vars:
        sys.stdout.write(css_vars(doc))
        return 0
    if args.overrides:
        return run_overrides(args, doc, skill_dir, project, tokens_file, root)
    if args.migrate:
        added = migrate(doc, P.read_plumb_md(root / "PLUMB.md").get("Project", ""))
        if not added:
            print(f"ok: {rel(tokens_file, root)} is at schema {P.SCHEMA_VERSION}, nothing to add")
            return 0
        text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
        if not _write(tokens_file, text, root):
            return 2
        for line in added:
            print(f"added {line}")
        print(f"wrote {rel(tokens_file, root)}")
        return 0
    if args.contrast:
        found = contrast_output(doc, skill_dir, required=True)
        assert found is not None
        path, text = found
        if read_dark_doc(skill_dir) == text:
            print(f"ok: the contrast block in {rel(path, root)} is up to date")
        else:
            if not _write(path, text, root):
                return 2
            print(f"wrote {rel(path, root)}")
        fails = text.count("| fail (")
        if fails:
            print(f"{fails} pair(s) fail: see the nearest passing values in {rel(path, root)}")
        return 0
    notes: List[str] = []
    firsts: List[Path] = []
    files = outputs(doc, skill_dir, project, tokens_file, notes, firsts)
    for line in template_notes(doc, skill_dir, missing=not args.check):
        print(line, file=sys.stderr)
    warning = palette_warning(doc, skill_dir, root, tokens_file)
    if warning:
        print(warning, file=sys.stderr)
    if P.find_template(skill_dir, SPECIMEN_TEMPLATE) is None:
        print(f"note: specimen.html was not written: templates/{SPECIMEN_TEMPLATE} is missing from the skill; "
              f"copy it from the Plumb plugin's assets/skill/templates/ (or run /plumb:upgrade)", file=sys.stderr)
    command = f"python3 {rel(skill_dir / SCRIPT_REL, root)}"
    # A specimen.html this script did not write is never replaced: everything else is built, the specimen is left as it
    # is, and the build says so (--check: exit 1).
    foreign = specimen_in_the_way(doc, root, files)
    foreign_lines: List[str] = []
    if foreign:
        files.pop(foreign)
        page, target = rel(foreign, root), rel(_free_name(foreign, ".before-plumb.html"), root)
        foreign_lines = [f"{page} (not written by build-tokens.py): left as it is, so the specimen was not updated",
                         f"fix: ask the user before moving it out of the way (mv {P.shell_word(page)} "
                         f"{P.shell_word(target)}), then run {command}"]
    stale = []
    for path, text in files.items():
        try:
            current = path.read_bytes() if path.exists() else None
        except OSError:
            current = None
        if current == text.encode("utf-8"):
            continue
        if args.check:
            # a checkout with CRLF line endings or a BOM (git autocrlf) is not stale; a plain build still rewrites it
            if current is None or P.normalise_text(current.decode("utf-8", errors="replace")) != P.normalise_text(text):
                stale.append(path)
            continue
        if not _write(path, text, root):
            return 2
        print(f"wrote {rel(path, root)}")
    if not args.check:
        for note in notes:
            print(note, file=sys.stderr)
        if foreign_lines:
            first, _, why = foreign_lines[0].partition(" ")
            print(f"warning: {first} is not Plumb's {why}\n{foreign_lines[1]}", file=sys.stderr)
    if args.check:
        if foreign_lines:
            print(f"not Plumb's: {foreign_lines[0]}\n{foreign_lines[1]}")
        if stale:
            prototype_pages = set(prototype_page_outputs(doc, root))  # generated pages that carry the plumb:theme region
            for path in stale:
                note = " (prototype token block)" if path in prototype_pages else ""
                print(f"stale: {rel(path, root)}{note}")
            for path in firsts:
                if path in stale:
                    print_first_block(path, files[path], root)
            print(f"fix: {command}")
            return 1
        if foreign_lines:
            return 1
        print(f"ok: {len(files)} generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
