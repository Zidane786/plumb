#!/usr/bin/env python3
"""build-tokens.py: turn the one tokens JSON into the web CSS, the SwiftUI / Jetpack Compose themes and the contrast evidence.

Usage: build-tokens.py [--check | --contrast | --migrate | --css-vars | --overrides [--apply]] [--root SKILL_DIR] [--project PATH]

Reads <skill>/assets/tokens/*.tokens.json (exactly one) and the web template, writes
<skill>/assets/platforms/web/tokens.css (+ tailwind.tokens.js for tailwind-v3) and, in each copy listed in
$extensions.plumb.web.copies (relative to the project root), Plumb's block: the same CSS between
`/* plumb:start — GENERATED by Plumb, do not edit inside */` and `/* plumb:end */`. Plumb owns only the block: a new
copy is the block alone; an existing file keeps every byte outside it (a file with no block gets it near the top, after
the statements that must stay first, with a note; a whole copy an older build generated becomes the block); when the
rest of the file imports Tailwind, the block leaves its own @import out. --check compares only the block. The template's
{{@dark}} / {{@dark-variant}} lines follow $extensions.plumb.web.theme_switch (both | system | class | data-theme, default both) and
{{@reduced-motion}} follows $extensions.plumb.motion.reduced (none | keep-fades, default none). It also writes
assets/platforms/mobile/ios/<Project>Theme.swift and
mobile/android/<Project>Theme.kt for the platforms listed in $extensions.plumb.platforms, and refreshes the block between
<!-- plumb:contrast:start --> and <!-- plumb:contrast:end --> in <skill>/references/dark-mode.md when that file has the markers,
and the specimen page <project>/<docs_dir>/specimen.html (docs_dir from $extensions.plumb, default docs/design) from
templates/specimen.html.tmpl: every token (colours light and dark side by side with their contrast pairs, type, spacing,
radii, shadows in both themes, motion, the rest) and the basic controls in every state in both themes, styled with the
project's own tokens, offline, no timestamps. --check covers it; with no template the build notes it and skips the page.
It also refreshes the token-derived region (between /* plumb:theme */ and /* plumb:theme:end */: the --css-vars token
block, the page roles, the frame breakpoint) inside <docs_dir>/prototype.html, app.html and screens.html when
build-prototype.py has written them (and in the proposal pages build-prototype.py --proposal wrote), so one tokens build
keeps every page in step; --check names a stale one as a prototype token block.

  --check      write nothing; exit 1 naming every stale or missing file.
  --contrast   rewrite only the contrast block of references/dark-mode.md (exit 2 if the file or the markers are missing).
  --migrate    bring the tokens JSON up to the current schema (1) by adding missing settings (and the defaults the build
               applies for a missing web.theme_switch / motion.reduced); never removes or changes a value.
  --overrides  print, as JSON, what each web copy sets in the tokens' namespaces outside Plumb's block (the audit's
               block-override), with the token each maps onto and the exact edits; --overrides --apply makes them
               (only after the user's OK).
  --css-vars   print the tokens as plain CSS custom properties (:root, the md breakpoint, .dark and prefers-color-scheme).

The default build prints one `note:` line to stderr when dark-mode.md exists without the markers.
Exit codes: 0 ok, 1 stale (--check), 2 bad input (error: ... then fix: ...).

Contrast pairs (WCAG 2.x, light and dark):
  * every on-X token over X (4.5:1);
  * every text token over every surface (4.5:1). Text tokens are colour tokens whose name starts with `on-`, is exactly
    `link`, or has `text` or `ink` as a whole hyphen-separated word (text-muted, primary-ink; not pink or context-menu).
    Surfaces are background, page, sidebar, sunk, column, surface*, and *-container, or exactly the tokens listed in
    $extensions.plumb.contrast.surfaces. An `on-X` token where X is itself a surface (on-surface, on-surface-variant,
    on-background) is checked over every surface; any other on-X (on-primary) is checked over its own X only;
  * UI boundaries (3:1): the token `outline-input` and tokens listed in contrast.ui, over every non-container surface;
  * contrast.extra_pairs, either form per entry:
      ["on-primary-fill", "primary-fill", "text"]            [fg, bg, kind], kind text (4.5) | large (3) | ui (3)
      {"fg": token, "bg": token, "need": 4.5, "note": "..."}  "need" defaults to 4.5 (3 for large text)
--contrast exits 0 even when pairs fail: it writes the evidence, the audit is the gate.
A failing pair lists the nearest passing foreground: its OKLCH lightness (hue kept) is stepped darker (light mode) or lighter (dark mode) until it
passes with FIX_SPARE (0.5) to spare, so the audit's contrast-headroom suggestion (under HEADROOM, 0.3) never flags it.

Python 3.9+, standard library only. Declarations follow the order of the tokens file
(deterministic, keeps the file's grouping). Imports the shared core _plumb.py from its own directory.
"""

