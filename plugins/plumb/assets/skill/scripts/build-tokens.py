def read_template(skill_dir: Path, styling: str) -> str:
    folder = skill_dir / "assets" / "platforms" / "web"
    for name in (TEMPLATE_NAME, f"{TEMPLATE_NAME}.{styling}"):
        path = folder / name
        if path.is_file():
            try:
                text = path.read_text(encoding="utf-8-sig")
            except (OSError, UnicodeDecodeError) as exc:
                raise _err(f"{path}: cannot read the template ({exc})", "save it as UTF-8") from None
            return text.replace("\r\n", "\n").replace("\r", "\n")
    raise _err(
        f"missing web template {folder / TEMPLATE_NAME}",
        f"copy {TEMPLATE_NAME}.{styling} from the Plumb plugin's assets/skill/assets/platforms/web/ to {folder / TEMPLATE_NAME}",
    )


def _lines(decls: List[Tuple[str, str]]) -> List[str]:
    return [f"{n}: {v};" for n, v in decls]


THEME_SWITCHES = ("both", "system", "class", "data-theme")
REDUCED_MOTION = ("none", "keep-fades")
# Tailwind v4's default theme namespaces the {{@reset-palette}} directive clears (web.reset_palette true): then only the
# tokens exist. An older template that spells the lines out loses them when reset_palette is false.
RESET_NAMESPACES = ("color", "radius", "shadow", "text", "font", "ease")
RESET_LINE = re.compile(r"^[ \t]*--(?:" + "|".join(RESET_NAMESPACES) + r")-\*\s*:\s*initial\s*;[ \t]*\n", re.M)
CLOSED_COMMENT = re.compile(r"^/\* Closed scales:.*?\*/[ \t]*\n", re.M | re.S)


def reset_palette(doc: dict) -> bool:
    """$extensions.plumb.web.reset_palette (default true): the block clears Tailwind's default colours, radii,
    shadows, text sizes, fonts and easings, so only the tokens exist. false keeps them (an existing app that still
    uses them renders as before; the audit suggests moving each palette class to a token)."""
    value = P.plumb_settings(doc)["web"].get("reset_palette", True)
    if not isinstance(value, bool):
        raise _err(f"$extensions.plumb.web.reset_palette is {value!r}",
                   "set it to true (only the tokens exist: Tailwind's default palette and scales are switched off) or "
                   "false (Tailwind's defaults stay until the app is migrated)")
    return value


def reset_palette_css(doc: dict) -> List[str]:
    """The {{@reset-palette}} directive: the namespace resets when web.reset_palette is true, else a comment saying
    Tailwind's defaults stay."""
    if not reset_palette(doc):
        return ["/* Open scales (web.reset_palette false): Tailwind's default colours, radii, shadows, text sizes, fonts",
                "   and easings stay available until the app is migrated to the tokens; the audit suggests each move. */"]
    return (["/* Closed scales (web.reset_palette true): Tailwind's default colours, radii, shadows, text sizes, fonts",
             "   and easings do not exist here, only the tokens. Spacing stays Tailwind's multiplier from the spacing",
             "   base token; the audit enforces the scale. */"]
            + [f"--{ns}-*: initial;" for ns in RESET_NAMESPACES])


def web_switches(doc: dict) -> Tuple[str, str]:
    """(theme switch, reduced motion) from $extensions.plumb.web.theme_switch (both | system | class | data-theme,
    default both)
    and $extensions.plumb.motion.reduced (none | keep-fades, default none)."""
    settings = P.plumb_settings(doc)
    switch = settings["web"].get("theme_switch", "both")
    if switch not in THEME_SWITCHES:
        raise _err(f"$extensions.plumb.web.theme_switch is {switch!r}",
                   'set it to "both" (the system setting, and the .dark / .light class), "system", "class" or '
                   '"data-theme" (data-theme="dark" / "light" on <html>, as next-themes sets it by default)')
    motion = settings.get("motion") if isinstance(settings.get("motion"), dict) else {}
    reduced = motion.get("reduced", "none")
    if reduced not in REDUCED_MOTION:
        raise _err(f"$extensions.plumb.motion.reduced is {reduced!r}",
                   'set it to "none" (no motion when the user asks for less) or "keep-fades" (opacity and colour fades '
                   'stay, movement stops)')
    return switch, reduced


def _rule(selector: str, body: List[str], indent: str = "") -> List[str]:
    return [f"{indent}{selector} {{"] + [f"{indent}  {b}" for b in body] + [f"{indent}}}"]


DATA_DARK, DATA_LIGHT = '[data-theme="dark"]', '[data-theme="light"]'


def dark_css(doc: dict) -> List[str]:
    """The dark scheme for the {{@dark}} directive, as web.theme_switch says: system = the OS setting
    (prefers-color-scheme) unless <html> has .light; class = .dark on <html> (or any element); both = either. A .light
    rule puts the light values back inside a dark page. data-theme = the attribute (data-theme="dark" | "light"),
    as next-themes sets it: [data-theme="dark"] and [data-theme="light"] only. Empty when no token has a dark value."""
    dark = declarations(doc, "dark")
    if not dark:
        return []
    switch, _reduced = web_switches(doc)
    names = {n for n, _v in dark}
    light = [(n, v) for n, v in declarations(doc, "light") if n in names]
    body = _lines(dark) + ["color-scheme: dark;"]
    out: List[str] = []
    if switch == "data-theme":
        out += ["/* Dark scheme from the data-theme attribute (on <html>, or on any element for that part of the page). */"]
        out += _rule(DATA_DARK, body)
        out += ["/* data-theme=\"light\" keeps or puts back the light values (for a light part inside a dark page). */"]
        return out + _rule(DATA_LIGHT, _lines(light) + ["color-scheme: light;"])
    if switch in ("system", "both"):
        out += ["/* Dark scheme from the system setting (prefers-color-scheme), unless <html> has the light class. */",
                "@media (prefers-color-scheme: dark) {"] + _rule(":root:not(.light)", body, "  ") + ["}"]
    if switch in ("class", "both"):
        out += ["/* Dark scheme from the dark class (on <html>, or on any element for that part of the page). */"]
        out += _rule(".dark", body)
    out += ["/* The light class keeps or puts back the light values (for a light part inside a dark page). */"]
    out += _rule(".light", _lines(light) + ["color-scheme: light;"])
    return out


def dark_variant_css(doc: dict) -> List[str]:
    """Tailwind v4's dark: variant for the {{@dark-variant}} directive, matching dark_css."""
    switch, _reduced = web_switches(doc)
    if switch == "class":
        return ["/* dark: follows the dark class (on <html>). Tokens switch by themselves, so components rarely need it. */",
                "@custom-variant dark (&:where(.dark, .dark *));"]
    if switch == "data-theme":
        return ["/* dark: follows data-theme=\"dark\" (on <html>). Tokens switch by themselves, so components rarely "
                "need it. */", f"@custom-variant dark (&:where({DATA_DARK}, {DATA_DARK} *));"]
    media = ["  @media (prefers-color-scheme: dark) {", "    &:where(:not(.light, .light *)) { @slot; }", "  }"]
    if switch == "system":
        return ["/* dark: follows the system setting unless the light class is set. Tokens switch by themselves, so "
                "components rarely need it. */", "@custom-variant dark {"] + media + ["}"]
    return ["/* dark: follows the dark class, or the system setting unless the light class is set. Tokens switch by "
            "themselves, so components rarely need it. */",
            "@custom-variant dark {", "  &:where(.dark, .dark *) { @slot; }"] + media + ["}"]


# Elements whose transition is only a fade: Tailwind's transition-opacity and transition-colors (they transition
# nothing else), and .motion-fade, the class a plain-CSS project puts on an element whose own transition is a fade.
FADE_CLASSES = (".transition-opacity", ".transition-colors", ".motion-fade")
# What a fade animates: opacity and the colours (Tailwind's transition-colors list).
FADE_PROPERTIES = ("opacity", "color", "background-color", "border-color", "outline-color", "text-decoration-color",
                   "fill", "stroke")


def reduced_motion_css(doc: dict) -> List[str]:
    """The prefers-reduced-motion block for the {{@reduced-motion}} directive, as $extensions.plumb.motion.reduced
    says: none = no animation or transition at all; keep-fades = an element whose transition is only a fade
    (FADE_CLASSES) keeps it as it is, and its ::before / ::after keep only their opacity and colour transitions (they
    are not marked, so they may move); every other transition and every animation stops; no element gains a
    transition it did not have."""
    _switch, reduced = web_switches(doc)
    if reduced == "keep-fades":
        keep = ", ".join(FADE_CLASSES)
        head = ["/* Motion is an enhancement. If the user asked for less, keep the fades and stop every movement: an",
                f"   element whose transition is only a fade ({keep}) keeps it, its ::before and",
                "   ::after keep only opacity and colour; every other transition and every animation stops. Nothing",
                "   gains a transition it did not have. Never override this block. */"]
        rules = ["animation-duration: 0s !important;", "animation-iteration-count: 1 !important;",
                 "scroll-behavior: auto !important;"]
        moving = f":not({keep})"
        stop = ["transition-duration: 0s !important;", "transition-delay: 0s !important;"]
        pseudos = ", ".join(f"{c}::{p}" for c in FADE_CLASSES for p in ("before", "after"))
        fade_only = [f"transition-property: {', '.join(FADE_PROPERTIES)} !important;"]
        return (head + ["@media (prefers-reduced-motion: reduce) {"] + _rule("*, ::before, ::after", rules, "  ")
                + _rule(f"{moving}, {moving}::before, {moving}::after", stop, "  ")
                + _rule(pseudos, fade_only, "  ") + ["}"])
    else:
        head = ["/* Motion is an enhancement. If the user asked for less, give them none. Never override this block. */"]
        rules = ["animation-duration: 0s !important;", "animation-iteration-count: 1 !important;",
                 "transition-duration: 0s !important;", "transition-delay: 0s !important;",
                 "scroll-behavior: auto !important;"]
    return head + ["@media (prefers-reduced-motion: reduce) {"] + _rule("*, ::before, ::after", rules, "  ") + ["}"]


def build_css(doc: dict, template: str, header: str) -> str:
    directives: Dict[str, Callable[[], List[str]]] = {
        "header": lambda: [header],
        "vars": lambda: _lines(declarations(doc, "light")),
        "vars-dark": lambda: _lines(declarations(doc, "dark")),
        "vars-md": lambda: _lines(declarations(doc, "md")),
        "dark": lambda: dark_css(doc),
        "dark-variant": lambda: dark_variant_css(doc),
        "reduced-motion": lambda: reduced_motion_css(doc),
        "reset-palette": lambda: reset_palette_css(doc),
    }
    if not reset_palette(doc):  # an older template spells the resets out: drop them (and its "Closed scales" note)
        template = CLOSED_COMMENT.sub("", RESET_LINE.sub("", template))

    def run_directive(name: str) -> List[str]:
        if name not in directives:
            raise _err(f"unknown template directive {{{{@{name}}}}}", f"use one of: {', '.join('@' + d for d in directives)}")
        return directives[name]()

    def block(m: "re.Match[str]") -> str:
        lines = run_directive(m.group(2))
        if not lines:
            return "\x00DROP\x00"
        return "\n".join(m.group(1) + line for line in lines)

    if not directives["vars-md"]():  # no md tokens: drop the whole {{@if-md}} ... {{@end}} section
        template = IF_MD.sub("", template)
    template = re.sub(r"^[ \t]*\{\{@(?:if-md|end)\}\}[ \t]*\n", "", template, flags=re.M)
    out = DIRECTIVE_LINE.sub(block, template)
    out = re.sub(r"\x00DROP\x00\n?", "", out)
    out = re.sub(r"\n{3,}", "\n\n", out)  # a dropped section leaves no run of blank lines
    out = DIRECTIVE_ANY.sub(lambda m: " ".join(run_directive(m.group(1))), out)

    def sub(m: "re.Match[str]") -> str:
        path, variant, flt = m.group(1), m.group(2), m.group(3)
        mode = {"@dark": "dark", "@md": "md"}.get(variant or "", "light")
        try:
            v = P.resolve(doc, path, mode)
        except PlumbError as exc:
            raise _err(f"template placeholder {m.group(0)}: {str(exc).splitlines()[0][len('error: '):]}",
                       "fix the name in the template or add the token to the tokens file") from None
        if flt == "percent":
            return num(round(float(v) * 100, 4)) + "%"
        if flt == "s":
            text = dimension_css(v)
            mm = re.fullmatch(r"([\d.]+)ms", text)
            if not mm:
                raise _err(f"{m.group(0)}: |s needs a duration in ms, got {text}", "use a duration token written like 150ms")
            return num(float(mm.group(1)) / 1000) + "s"
        if flt:
            raise _err(f"unknown filter |{flt} in {m.group(0)}", "use |percent or |s")
        token_type = _type_of(doc, path)
        return value_css(v, token_type)

    out = PLACEHOLDER.sub(sub, out)
    left = re.search(r"\{\{[^}]*\}\}", out)
    if left:
        raise _err(f"unresolved placeholder in the template: {left.group(0)}", "use {{group.token}}, {{group.token@dark}} or {{@vars}}")
    if "GENERATED by" not in out[:400]:
        out = f"/* {header} */\n" + out
    return out


def _type_of(doc: dict, path: str) -> Optional[str]:
    for p, _tok, ttype in P.iter_tokens(doc):
        if p == path:
            return ttype
    parent = path.rsplit(".", 1)[0]  # a field of a composite, e.g. typography.sm.fontSize
    for p, _tok, ttype in P.iter_tokens(doc):
        if p == parent:
            field = path.rsplit(".", 1)[1]
            return FIELD_TYPES.get(field)
    return None


