def _prefixed_token(colors: dict, name: str) -> Optional[str]:
    """The tokens' own role for a sidebar-<x> / sidebar-<x>-foreground name: color.sidebar-<role> /
    color.on-sidebar-<role>, <role> being <x> or its known synonym (accent <-> active). None when there is none."""
    for prefix in _ROLE_PREFIXES:
        if not name.startswith(prefix) or len(name) <= len(prefix):
            continue
        group = prefix[:-1]
        rest = name[len(prefix):]
        foreground = rest.endswith("-foreground")
        base = rest[:-len("-foreground")] if foreground else rest
        for role in (base,) + _SIDEBAR_SYNONYMS.get(base, ()):
            cand = f"on-{group}-{role}" if foreground else f"{group}-{role}"
            if P.is_token(colors.get(cand)):
                return cand
    return None


def _role_token(colors: dict, name: str) -> Optional[str]:
    """The colour token a project's colour name means: a sidebar-specific token first, then its own role table, on-X
    for X-foreground, and a sidebar-<x> name as <x> (sidebar-primary -> primary)."""
    specific = _prefixed_token(colors, name)
    if specific:
        return specific
    for cand in _ROLE_NAMES.get(name, ()):
        if P.is_token(colors.get(cand)):
            return cand
    if name.endswith("-foreground"):
        base = name[:-len("-foreground")]
        for cand in (f"on-{base}",) + tuple(f"on-{r}" for r in _ROLE_NAMES.get(base, ())):
            if P.is_token(colors.get(cand)):
                return cand
    for prefix in _ROLE_PREFIXES:
        if name.startswith(prefix) and len(name) > len(prefix):
            rest = name[len(prefix):]
            return rest if P.is_token(colors.get(rest)) else _role_token(colors, rest)
    return None


COLOUR_TOLERANCE = 2  # per sRGB channel (0-255): oklch read twice may round one step apart


def _rgba(text: object) -> Optional[Tuple[int, int, int, float]]:
    try:
        hexv, alpha = P.parse_color(str(text))
    except (PlumbError, ValueError, TypeError):
        return None
    h = hexv.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), float(alpha)


def _same_colour(a: Optional[tuple], b: Optional[tuple]) -> bool:
    if a is None or b is None:
        return False
    return all(abs(x - y) <= COLOUR_TOLERANCE for x, y in zip(a[:3], b[:3])) and abs(a[3] - b[3]) <= 0.02


def _token_colours(doc: dict, path: str) -> Optional[Tuple[tuple, tuple]]:
    """(light, dark) of a colour token as (r, g, b, alpha), or None when it does not resolve to colours."""
    try:
        light, dark = _rgba(P.resolve(doc, path, "light")), _rgba(P.resolve(doc, path, "dark"))
    except PlumbError:
        return None
    return (light, dark) if light is not None and dark is not None else None


def _app_colours(values: Dict[str, str], value: str) -> Optional[Tuple[tuple, tuple]]:
    """The app's (light, dark) for a variable (dark = light when the app sets it only once), or None."""
    light = _rgba(values.get("light") or value)
    if light is None:
        return None
    dark = _rgba(values["dark"]) if values.get("dark") else light
    return (light, dark) if dark is not None else None


def _is_text_token(name: str) -> bool:
    """A colour token for text or icons: on-*, text*, *-ink, link (the contrast pairs' rule)."""
    parts = name.split("-")
    return name.startswith("on-") or name == "link" or "text" in parts or "ink" in parts


_LINE_PARTS = ("outline", "border", "ring", "divider", "stroke", "input")


def _colour_family(name: str) -> str:
    """What a colour is for, so a value match never crosses roles: "text" (text and icons: on-*, *-foreground, text,
    ink, link), "line" (borders, outlines, rings, dividers, input borders) or "fill" (backgrounds and surfaces)."""
    parts = name.split("-")
    if _is_text_token(name) or name.endswith("-foreground") or name in ("foreground", "fg"):
        return "text"
    if any(p in parts for p in _LINE_PARTS):
        return "line"
    return "fill"


def _show(cols: Optional[Tuple[tuple, tuple]]) -> str:
    """light / dark as #rrggbb[aa]."""
    if cols is None:
        return "unknown"

    def one(c: tuple) -> str:
        return "#%02x%02x%02x" % c[:3] + ("" if c[3] >= 1 else "%02x" % round(c[3] * 255))

    return one(cols[0]) if cols[0] == cols[1] else f"{one(cols[0])} / {one(cols[1])}"


def _colour_value(text: str) -> str:
    """A project's colour as a token value: #rrggbb, or #rrggbbaa when it is translucent (oklch(... / 10%))."""
    hexv, alpha = P.parse_color(text)
    return hexv if alpha >= 1 else hexv + f"{round(alpha * 255):02x}"


_CALC_RADIUS = re.compile(r"^(?:var\(\s*(--[\w-]+)\s*\)|calc\(\s*var\(\s*(--[\w-]+)\s*\)\s*([+-])\s*(\d*\.?\d+)px\s*\))$")


def _px(text: str) -> Optional[float]:
    m = re.fullmatch(r"\s*(\d*\.?\d+)(px|rem)\s*", text or "")
    if not m:
        return None
    return float(m.group(1)) * (16 if m.group(2) == "rem" else 1)


def _font_stack(name: str) -> List[str]:
    key = "mono" if "mono" in name else "serif" if "serif" in name and "sans" not in name else "sans"
    return list(_FONT_STACKS[key])


def _squash(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


class _Lines:
    """Line numbers (1-based) and whole-line tests for one stylesheet."""

    def __init__(self, text: str, code: str) -> None:
        self.text, self.code = text, code
        self.starts = [0] + [m.end() for m in re.finditer("\n", text)]
        span = P.block_span(text)
        # Plumb's own block (masked to spaces in `code`): never removed, never counted as a blank line
        self.block = range(self.line(span[0]), self.line(span[1] - 1) + 1) if span else range(0)

    def line(self, pos: int) -> int:
        return bisect_right(self.starts, pos)

    def span(self, line: int) -> Tuple[int, int]:
        start = self.starts[line - 1]
        end = self.starts[line] - 1 if line < len(self.starts) else len(self.text)
        return start, end

    def alone(self, start: int, end: int) -> bool:
        """code[start:end] is all the code on the lines it covers."""
        a, _ = self.span(self.line(start))
        _, b = self.span(self.line(max(start, end - 1)))
        return not self.code[a:start].strip() and not self.code[end:b].strip()

    def lines(self, start: int, end: int) -> List[int]:
        return list(range(self.line(start), self.line(max(start, end - 1)) + 1))

    def blank(self, line: int) -> bool:
        """No code on the line (a comment-only line counts); never a line of Plumb's block."""
        a, b = self.span(line)
        return line not in self.block and not self.code[a:b].strip()

    def empty(self, line: int) -> bool:
        """A really empty line of the file (whitespace only), outside Plumb's block."""
        a, b = self.span(line)
        return line not in self.block and not self.text[a:b].strip()


def _enclosing(blocks: list, pos: int) -> List[tuple]:
    return [b for b in blocks if b[1] < pos < b[2]]


USES_SHOWN = 20  # per variable


def _uses_elsewhere(root: Path, copy: Path, project_vars: List[dict], docs_rel: str = "docs/design") -> None:
    """Fill each project variable's used_in with the other UI files (file:line) that still read var(--x): the plan
    removes it from the copy, so the skill shows these and points them at the token's variable too, after asking.
    Plumb's own pages (the docs folder: extract.html, the specimen, the prototype) and the design-system skill are not
    the app: they are never listed."""
    if not project_vars:
        return
    docs = (root / docs_rel.replace("\\", "/").strip("/")).resolve() if docs_rel.strip("/") else None
    pattern = re.compile(r"var\(\s*(" + "|".join(re.escape(v["name"]) for v in project_vars) + r")\s*[),]")
    by_name = {v["name"]: v for v in project_vars}
    skip = copy.resolve()
    for dirpath, dirnames, filenames in os.walk(root):
        here = Path(dirpath)
        if docs is not None and (here.resolve() == docs or docs in here.resolve().parents):
            dirnames[:] = []
            continue
        dirnames[:] = sorted(d for d in dirnames if d not in P.SKIP_DIRS and not (d == "skills" and here.name == ".claude"))
        for fname in sorted(filenames):
            path = here / fname
            if P.source_ext(fname) is None or path.resolve() == skip:
                continue
            try:
                if path.stat().st_size > P.MAX_SOURCE_BYTES:
                    continue
                text = path.read_bytes().decode("utf-8", errors="replace")
            except OSError:
                continue
            if "var(" not in text or P.is_generated_text(text[:2000]):
                continue
            for m in pattern.finditer(text):
                used = by_name[m.group(1)]["used_in"]
                if len(used) < USES_SHOWN:
                    used.append(f"{rel(path, root)}:{text.count(chr(10), 0, m.start()) + 1}")


def _jsx_tags(text: str, name: str) -> List[Tuple[int, int]]:
    """(start, end) of every opening <name ...> tag in JSX text (braces balanced, so an arrow's > does not end it)."""
    out: List[Tuple[int, int]] = []
    for m in re.finditer(r"<" + name + r"(?=[\s>])", text):
        depth = 0
        for i in range(m.end(), len(text)):
            c = text[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            elif c == ">" and depth <= 0:
                out.append((m.start(), i + 1))
                break
    return out


_FONT_CALL = re.compile(r"(?<![\w$.])([A-Za-z_$][\w$]*)\s*=\s*[\w$.]+\s*\(")
_FONT_VARIABLE = re.compile(r"\bvariable\s*:\s*[\"'](--[\w-]+)[\"']")
_IMPORT_NAMES = re.compile(r"import\s*\{([^}]*)\}\s*from\s*[\"'](\.{1,2}/[^\"']+)[\"']")
_VARIABLE_USE = re.compile(r"(?<![\w$])([A-Za-z_$][\w$]*)\.variable\b")


def _font_variables(code: str) -> Dict[str, str]:
    """identifier -> the CSS variable its `ident = Font({ ..., variable: "--font-x" })` call declares (any options, a
    nested src array included: the call's arguments are read up to the matching parenthesis)."""
    out: Dict[str, str] = {}
    for m in _FONT_CALL.finditer(code):
        depth, i = 1, m.end()
        while i < len(code) and depth:
            depth += {"(": 1, ")": -1}.get(code[i], 0)
            i += 1
        found = _FONT_VARIABLE.search(code, m.end(), i)
        if found:
            out[m.group(1)] = found.group(1)
    return out


def _local_module(root: Path, base: Path, spec: str) -> Optional[Path]:
    """The project file a relative import names (one hop, inside the project), or None."""
    target = base / spec
    exts = (".ts", ".tsx", ".js", ".jsx")
    for cand in [target] + [target.with_name(target.name + e) for e in exts] + [target / f"index{e}" for e in exts]:
        try:
            cand = cand.resolve()
            if cand.is_file() and root.resolve() in cand.parents:
                return cand
        except OSError:
            continue
    return None


def _tag_uses(code: str, tag: str) -> Dict[str, int]:
    """`ident.variable` uses inside the opening <tag ...> tags of a JSX file: ident -> offset of its first use."""
    found: Dict[str, int] = {}
    for start, end in _jsx_tags(code, tag):
        for m in _VARIABLE_USE.finditer(code, start, end):
            found.setdefault(m.group(1), m.start())
    return found


def _next_font_body_notes(root: Path, fontvars: Dict[str, str]) -> List[str]:
    """by_hand items for next/font variables the app applies on <body> instead of <html>: the tokens' font stack reads
    var(--font-x) on :root, where it is undefined, so the whole stack is invalid. Reads the root layout of each
    `next-app` entry of PLUMB.md's `Routes:` only (no Routes, another kind or no layout file: nothing); a font defined
    in the layout or in a local file it imports from (one relative hop) is checked, any other is named as unchecked."""
    if not fontvars:
        return []
    try:
        routes, _problems = P.parse_routes(P.read_plumb_md(root / "PLUMB.md").get("Routes"))
    except PlumbError:
        return []
    layouts: Dict[Path, None] = {}
    for route, kind in routes or []:
        if kind == "next-app":
            found = next((root / route / f"layout.{e}" for e in ("tsx", "jsx", "js", "ts")
                          if (root / route / f"layout.{e}").is_file()), None)
            if found:
                layouts[found] = None
    notes: List[str] = []
    for layout in layouts:
        try:
            text = layout.read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        code = P.mask_comments(text, ".tsx")  # same offsets: a <body> in a comment is not the tag
        on_body, on_html = _tag_uses(code, "body"), _tag_uses(code, "html")
        defs = _font_variables(code)
        imports: Dict[str, Tuple[str, str]] = {}  # local name -> (imported name, module specifier)
        for m in _IMPORT_NAMES.finditer(code):
            for item in m.group(1).split(","):
                names = item.strip().split(" as ")
                if names[0].strip():
                    imports[names[-1].strip()] = (names[0].strip(), m.group(2))
        for ident, pos in on_body.items():
            if ident in on_html:
                continue
            where = f"{rel(layout, root)}:{text.count(chr(10), 0, pos) + 1}"
            var = defs.get(ident)
            if var is None and ident in imports:
                imported, spec = imports[ident]
                module = _local_module(root, layout.parent, spec)
                try:
                    var = _font_variables(module.read_bytes().decode("utf-8")).get(imported) if module else None
                except (OSError, UnicodeDecodeError):
                    var = None
            if var in fontvars:
                notes.append(f"{where}: {ident}.variable (the font behind var({var})) is applied on <body>, but the "
                             f"tokens' font stack reads var({var}) on :root, where it is undefined: move "
                             f"`{ident}.variable` to the `<html>` className in {where}")
            elif var is None:
                names = " or ".join(f"var({v})" for v in fontvars)
                notes.append(f"{where}: {ident}.variable is applied on <body> and Plumb could not see where {ident} is "
                             f"defined (only the layout and the local file it imports it from are read): if it is the "
                             f"font behind {names}, move it to the `<html>` className, because on :root that "
                             f"variable is undefined and the whole font stack is invalid")
    return notes


def copy_override_plan(doc: dict, path: Path, root: Path) -> dict:
    """What moves where for one web copy: each override (line, name, value, kind token | new-name | namespace |
    dark-variant, the token it is or becomes, the project's values, the token change), the lines to remove, the
    replacements, the project variables that fed them, and what only the person can do (by_hand)."""
    shown = rel(path, root)
    text = path.read_bytes().decode("utf-8")
    code = P.mask_comments(P.mask_block(text), ".css")
    L = _Lines(text, code)
    blocks = P.css_blocks(code)
    themes = [(s, s + len(body)) for s, body in P.theme_bodies(code)]
    in_theme = lambda pos: any(a <= pos < b for a, b in themes)  # noqa: E731
    tokvars = {varname(p): (p, ty) for p, _t, ty in P.iter_tokens(doc)}
    # the colour tokens by the name their variable has (color.sidebar.active -> sidebar-active) and where each lives
    colors: Dict[str, dict] = {}
    cpaths: Dict[str, str] = {}
    for tpath, tok, ttype in P.iter_tokens(doc):
        parts = P.path_parts(tpath)
        if ttype == "color" and parts[0] == "color" and len(parts) > 1:
            colors.setdefault("-".join(parts[1:]), tok)
            cpaths.setdefault("-".join(parts[1:]), tpath)
    cpath = lambda name: cpaths.get(name, f"color.{name}")  # noqa: E731
    overrides: List[dict] = []
    remove: set = set()
    by_hand: List[str] = []
    notes: List[str] = []  # what the plan decided for the person to know (not to decide)
    feeds: Dict[str, str] = {}  # project variable -> the token variable it fed
    fontvars: Dict[str, str] = {}  # a font variable the app defines elsewhere (next/font) -> the token variable that reads it
    def project_values(name: str, value: str) -> Tuple[Optional[str], list, Dict[str, str]]:
        """(the project variable it reads, its declarations outside @theme, its light and dark values)."""
        src_m = _VAR_ONLY.fullmatch(value)
        src = src_m.group(1) if src_m else None
        decls = [d for d in re.finditer(r"(?<![\w-])" + re.escape(src) + r"\s*:\s*([^;{}]*);?", code)
                 if not in_theme(d.start())] if src else []
        values: Dict[str, str] = {}
        for d in decls:
            mode = "dark" if any(_DARK_PRELUDE.search(code[b[0]:b[1]]) for b in _enclosing(blocks, d.start())) else "light"
            values.setdefault(mode, text[d.start(1):d.end(1)].strip())
        return src, decls, values

    def app_px(value: str) -> Optional[float]:
        """A length the app sets, in px: 6px / 0.5rem, var(--x), or calc(var(--x) ± Npx) with --x set outside @theme."""
        calc = _CALC_RADIUS.match(value)
        base_var = (calc.group(1) or calc.group(2)) if calc else None
        base = None
        if base_var:
            for d in re.finditer(r"(?<![\w-])" + re.escape(base_var) + r"\s*:\s*([^;{}]*);?", code):
                if not in_theme(d.start()):
                    base = _px(text[d.start(1):d.end(1)])
                    break
        if base is None and _px(value) is not None:
            base, calc = _px(value), None
        if base is None:
            return None
        px = base if not (calc and calc.group(3)) else (
            base + float(calc.group(4)) if calc.group(3) == "+" else base - float(calc.group(4)))
        return max(px, 0)

    # The app's colours, by name, so each role is checked against them (a role whose token has other colours would
    # change the app's look) and a sidebar-<x> name follows what <x> becomes.
    app: Dict[str, Optional[Tuple[tuple, tuple]]] = {}
    for pos, name in P.block_overrides(text):
        if name.startswith("--color-") and "*" not in name and name not in tokvars:
            m = re.compile(re.escape(name) + r"\s*:\s*([^;{}]*);?").match(code, pos)
            value = text[m.start(1):m.end(1)].strip() if m else ""
            app[name[len("--color-"):]] = _app_colours(project_values(name, value)[2], value)
    decided: Dict[str, Tuple[str, Optional[str]]] = {}  # rest -> ("alias", token name) | ("own", None)
    looks: List[str] = []  # names whose role token has other colours than the app

    def decide(rest: str) -> Tuple[str, Optional[str]]:
        """How a project colour name moves into the tokens: ("alias", token) when a token has its colours (its role
        token first: card -> surface, popover -> surface-raised or surface; then any token with the same light and
        dark colours; a sidebar-<x> with <x>'s colours follows <x>), else ("own", why) to add the app's own values."""
        if rest in decided:
            return decided[rest]
        decided[rest] = ("own", None)  # a guard against a loop
        mine = app.get(rest)
        out: Tuple[str, Optional[str]] = ("own", None)
        specific = _prefixed_token(colors, rest)
        if specific:  # the tokens have this sidebar role: it wins over the generic role and over a value match
            cols = _token_colours(doc, cpath(specific))
            if mine is not None and cols is not None and not (_same_colour(mine[0], cols[0]) and _same_colour(mine[1], cols[1])):
                looks.append(rest)
            decided[rest] = ("alias", specific)
            return decided[rest]
        for prefix in _ROLE_PREFIXES:
            base = rest[len(prefix):] if rest.startswith(prefix) else ""
            if base and (mine is None or (app.get(base) and _same_colour(mine[0], app[base][0])
                                          and _same_colour(mine[1], app[base][1]))):
                if base in app:
                    kind, tok = decide(base)
                    decided[rest] = ("alias", tok if kind == "alias" else base)
                    if base in looks:
                        looks.append(rest)
                    return decided[rest]
        role = _role_token(colors, rest)
        role_cols = _token_colours(doc, cpath(role)) if role else None
        if role and (mine is None or role_cols is None or
                     (_same_colour(mine[0], role_cols[0]) and _same_colour(mine[1], role_cols[1]))):
            out = ("alias", role)
        else:
            family = "text" if rest in ("text",) else _colour_family(rest)
            same = [k for k in colors if mine is not None and not k.startswith("$") and P.is_token(colors.get(k))
                    and _colour_family(k) == family  # never across roles: a background never becomes a border
                    and (lambda c: c is not None and _same_colour(mine[0], c[0]) and _same_colour(mine[1], c[1]))(
                        _token_colours(doc, cpath(k)))]
            if same:  # a token already has the app's exact colours (extract recorded them): keep the look
                out = ("alias", same[0])
            elif role:  # the role token (create: the new design replaces the stock colours; extract: say so)
                out = ("alias", role)
                looks.append(rest)
        decided[rest] = out
        return out

    for pos, name in P.block_overrides(text):
        line = L.line(pos)
        if name == "@custom-variant dark":
            end = code.find(";", pos)
            end = len(code) if end < 0 else end + 1
            entry = {"line": line, "name": name, "value": " ".join(code[pos:end].split()), "kind": "dark-variant",
                     "token": None, "project_values": {}, "token_change": None}
            if L.alone(pos, end):
                remove.update(L.lines(pos, end))
            else:
                by_hand.append(f"line {line}: delete {name} by hand (it shares its line with other code)")
            overrides.append(entry)
            continue
        m = re.compile(re.escape(name) + r"\s*:\s*([^;{}]*);?").match(code, pos)
        end = m.end() if m else pos + len(name)
        value = text[m.start(1):m.end(1)].strip() if m else ""
        ns, _, rest = name[2:].partition("-")
        group = _NS_GROUP.get(ns, ns)
        src, decls, values = project_values(name, value)
        change: Optional[dict] = None
        note = ""
        if "*" in name:
            kind, token = "namespace", None
        elif name in tokvars:
            kind, (token, ttype) = "token", tokvars[name]
            if ttype == "fontFamily" and src and not decls:
                fams = P.resolve(doc, token)
                fams = fams if isinstance(fams, list) else [fams]
                first = next((str(f) for f in fams if str(f).lower() not in SYSTEM_FAMILIES), "")
                if f"var({src})" in [str(f) for f in fams]:
                    fontvars.setdefault(src, name)
                elif not first or _squash(first) in _squash(src[2:].replace("font-", "", 1)):
                    # the tokens name only a system stack (or this very font): the app's own font goes first
                    change = {"prepend": token, "family": f"var({src})"}
                    fontvars.setdefault(src, name)
                else:
                    note = (f"line {line}: the app loads its font through var({src}), but {token} is {first!r}: "
                            f"ask the user which font to keep; to keep the app's, put var({src}) first in {token} "
                            f"(/plumb:update)")
            # the line goes and the token's value takes over: when the app's value is another, the look changes
            elif ttype == "color":
                mine, theirs = _app_colours(values, value), _token_colours(doc, token)
                if mine is not None and theirs is not None and not (
                        _same_colour(mine[0], theirs[0]) and _same_colour(mine[1], theirs[1])):
                    notes.append(f"line {line}: {name} is {{{token}}}, whose colours differ from the app's "
                                 f"({_show(mine)} today, {_show(theirs)} in the tokens): the look changes; ask the "
                                 f"user, or set {token} to the app's colours with /plumb:update")
            elif ttype == "dimension":
                mine_px, their_px = app_px(value), P._px(P.resolve(doc, token))
                if mine_px is not None and their_px is not None and abs(mine_px - their_px) > 0.01:
                    notes.append(f"line {line}: {name} is {{{token}}}, whose size differs from the app's "
                                 f"({num(mine_px)}px today, {num(their_px)}px in the tokens): the look changes; ask "
                                 f"the user, or set {token} to {num(mine_px)}px with /plumb:update")
        else:
            kind, token = "new-name", f"{group}.{rest}"
            if ns == "color" and rest:
                how, what = decide(rest)
                if how == "alias":
                    change = {"add": token, "$value": f"{{{cpath(what)}}}"}
                    if rest in looks:
                        notes.append(f"line {line}: {name} becomes {{{cpath(what)}}} (its role), whose colours differ "
                                     f"from the app's ({_show(app.get(rest))} today, {_show(_token_colours(doc, cpath(what)))} "
                                     f"in the tokens): the look changes; ask the user, or keep the app's colours as a "
                                     f"token of its own with /plumb:update")
                else:
                    try:
                        change = {"add": token, "$value": _colour_value(values.get("light") or value)}
                        if values.get("dark"):
                            change["$extensions"] = {"plumb": {"dark": _colour_value(values["dark"])}}
                        else:  # what the app does today: the same colour in dark, recorded as a decision
                            change["$extensions"] = {"plumb": {"same-in-dark": True}}
                            notes.append(f"line {line}: {name} has no dark value in the app; kept the same in dark "
                                         f"(same-in-dark) — change it with /plumb:update")
                    except PlumbError:
                        change = None
            elif ns == "radius" and rest:
                px = app_px(value)
                if px is not None:
                    change = {"add": token, "$value": f"{num(px)}px"}
            elif ns == "font" and rest:
                if src and not decls:
                    change = {"add": token, "$value": [f"var({src})"] + _font_stack(rest)}
                    fontvars.setdefault(src, name)
                elif not src and value and "var(" not in value:
                    change = {"add": token, "$value": [f.strip().strip("\"'") for f in value.split(",") if f.strip()]}
            if change is None:
                note = (f"line {line}: {name} is not a token and Plumb cannot tell which token it means: ask the user "
                        f"whether to add a {group} token for it (/plumb:update) or delete it")
        if note:
            by_hand.append(note)
        entry = {"line": line, "name": name, "value": value, "kind": kind, "token": token, "project_values": values,
                 "token_change": change}
        overrides.append(entry)
        if kind == "new-name" and change is None:
            continue  # nothing to move it to yet: the line stays until the person decides
        if not L.alone(pos, end):
            by_hand.append(f"line {line}: {name} shares its line with other code: move it into the tokens and delete it "
                           f"by hand")
            continue
        remove.update(L.lines(pos, end))
        if src and decls:
            feeds.setdefault(src, name)
    by_hand.extend(_next_font_body_notes(root, fontvars))
    # the project variables that only fed the overrides: their declarations go, their uses point at the token
    replace: List[dict] = []
    project_vars: List[dict] = []
    for src, name in feeds.items():
        decls = [d for d in re.finditer(r"(?<![\w-])" + re.escape(src) + r"\s*:\s*[^;{}]*;?", code)
                 if not in_theme(d.start())]
        lines = [L.line(d.start()) for d in decls]
        if all(L.alone(d.start(), d.end()) for d in decls):
            for d in decls:
                remove.update(L.lines(d.start(), d.end()))
        else:
            by_hand.append(f"{src} (line {', '.join(map(str, lines))}) shares a line with other code: delete it by hand")
        for u in re.finditer(r"var\(\s*" + re.escape(src) + r"\s*([),])", code):
            if L.line(u.start()) in remove:
                continue  # an override that goes (a use left in one that stays, calc(var(--radius) - 4px), changes)
            replace.append({"line": L.line(u.start()), "old": text[u.start():u.end()], "new": f"var({name}{u.group(1)}",
                            "why": f"{src} fed {name}, which is now the token's variable"})
        project_vars.append({"name": src, "declared": lines, "maps_to": name, "used_in": []})
    _uses_elsewhere(root, path, project_vars, str(P.plumb_settings(doc).get("docs_dir") or "docs/design"))
    # a literal font stack outside the tokens (body { font-family: Arial, ... }) uses the font token instead
    for f in re.finditer(r"(?<![\w-])font-family\s*:\s*([^;{}]+)", code):
        val = text[f.start(1):f.end(1)].strip()
        if "var(" in val or in_theme(f.start()) or L.line(f.start()) in remove:
            continue
        if any(re.match(r"\s*@font-face\b", code[b[0]:b[1]]) for b in _enclosing(blocks, f.start())):
            continue
        want = "--font-mono" if "monospace" in val.lower() else "--font-sans"
        if want not in tokvars and not any(o["name"] == want and o["token_change"] for o in overrides):
            continue
        replace.append({"line": L.line(f.start()), "old": val, "new": f"var({want})",
                        "why": f"a font stack outside the tokens: {tokvars.get(want, (want,))[0]} decides the font"})
    replace.sort(key=lambda r: r["line"])
    # blocks the removals leave empty go too, then one of the two blank lines they leave
    changed = True
    while changed:
        changed = False
        for pre, op, cl in blocks:
            first = pre + (len(code[pre:op]) - len(code[pre:op].lstrip()))
            inner = range(L.line(op) + 1, L.line(cl))
            lines = range(L.line(first), L.line(cl) + 1)
            if lines[0] in remove and lines[-1] in remove:
                continue
            touched = any(n in remove for n in inner)
            empty = all(n in remove or L.blank(n) for n in inner) and not code[op + 1:L.span(L.line(op))[1]].strip()
            if L.line(op) == L.line(cl):
                empty, touched = not code[op + 1:cl].strip(), False
            if touched and empty and L.alone(first, cl + 1):
                remove.update(lines)
                changed = True
    total = len(L.starts)
    for n in sorted(remove):
        if n + 1 in remove or n + 1 > total:
            continue
        before = n - 1
        while before in remove:
            before -= 1
        if (before < 1 or L.empty(before)) and L.empty(n + 1):
            remove.add(n + 1)
    remove -= set(L.block)  # Plumb's block is never the plan's to change
    return {"file": shown, "overrides": overrides, "remove_lines": sorted(remove), "replace": replace,
            "project_variables": project_vars, "by_hand": by_hand, "notes": notes}


def override_plans(doc: dict, skill_dir: Path, project: Optional[Path]) -> List[Tuple[Path, dict]]:
    root = find_project_root(skill_dir, project)
    out = []
    for copy in P.plumb_settings(doc)["web"].get("copies") or []:
        path = safe_copy_path(root, copy)
        if path.is_file():
            out.append((path, copy_override_plan(doc, path, root)))
    return out


def apply_override_plan(path: Path, plan: dict) -> Optional[str]:
    """The copy's new text after the plan's replacements and removals (None when nothing changes)."""
    text = path.read_bytes().decode("utf-8")
    lines = text.split("\n")
    for r in plan["replace"]:
        lines[r["line"] - 1] = lines[r["line"] - 1].replace(r["old"], r["new"], 1)
    drop = set(plan["remove_lines"])
    new = "\n".join(line for i, line in enumerate(lines, 1) if i not in drop)
    if P.block_text(new) != P.block_text(text):
        raise _err(f"{plan['file']}: the plan would change Plumb's block, so nothing was written",
                   f"run python3 {SCRIPT_REL} --overrides again and move the listed lines by hand")
    return None if new == text else new


def apply_token_changes(doc: dict, plans: List[dict]) -> List[str]:
    """Make each override's token change in `doc`; returns what changed."""
    done: List[str] = []
    for plan in plans:
        for o in plan["overrides"]:
            change = o.get("token_change")
            if not change:
                continue
            if "add" in change:
                parts = change["add"].split(".")
                node = doc
                for i, part in enumerate(parts[:-1]):
                    if not isinstance(node.get(part), dict):
                        node[part] = {"$type": _GROUP_TYPE[part]} if i == 0 and part in _GROUP_TYPE else {}
                    node = node[part]
                if parts[-1] in node:
                    continue
                node[parts[-1]] = {k: v for k, v in change.items() if k != "add"}
                done.append(f"added {change['add']} = {json.dumps(change['$value'], ensure_ascii=False)}")
            elif "prepend" in change:
                token, _rest, _ty = P._find(doc, change["prepend"])
                value = token["$value"] if isinstance(token["$value"], list) else [token["$value"]]
                if change["family"] not in value:
                    token["$value"] = [change["family"]] + value
                    done.append(f"changed {change['prepend']}: {change['family']} first (the font the app loads)")
    return done


def run_overrides(args: argparse.Namespace, doc: dict, skill_dir: Path, project: Optional[Path], tokens_file: Path,
                  root: Path) -> int:
    plans = override_plans(doc, skill_dir, project)
    if not args.apply:
        print(json.dumps({"copies": [p for _path, p in plans]}, indent=2, ensure_ascii=False))
        return 0
    if not any(p["overrides"] for _path, p in plans):
        print("ok: nothing to move: no web copy sets the tokens' variables outside Plumb's block")
        return 0
    news = [apply_override_plan(path, plan) for path, plan in plans]  # all checked before anything is written
    changes = apply_token_changes(doc, [p for _path, p in plans])
    if changes and not _write(tokens_file, json.dumps(doc, indent=2, ensure_ascii=False) + "\n", root):
        return 2
    for line in changes:
        print(line)
    for (path, plan), new in zip(plans, news):
        if new is not None:
            with open(path, "w", encoding="utf-8", newline="") as fh:
                fh.write(new)
            print(f"wrote {plan['file']}")
        for v in plan["project_variables"]:
            if v["used_in"]:
                print(f"note: var({v['name']}) is gone from {plan['file']} but still read at {', '.join(v['used_in'])}: "
                      f"ask the user, then point those at var({v['maps_to']})")
        for note in plan["notes"]:
            print(f"note: {plan['file']} {note}")
        for note in plan["by_hand"]:
            print(f"by hand: {plan['file']} {note}")
    print(f"next: python3 {rel(skill_dir / SCRIPT_REL, root)} (rebuild), then the audit")
    return 0


