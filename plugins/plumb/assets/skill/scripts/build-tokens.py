class Pair:
    def __init__(self, fg: str, bg: str, need: float) -> None:
        self.fg, self.bg, self.need = fg, bg, need
        self.light = 0.0
        self.dark = 0.0
        self.fix: Dict[str, Optional[Tuple[str, float]]] = {}
        # on-X on X where on-X is (near) white or black: the X stepped (same hue) until on-X passes unchanged, per mode
        self.fix_bg: Dict[str, Optional[Tuple[str, float]]] = {}
        self.fg_path = self.bg_path = ""
        self.hex: Dict[str, Tuple[str, str]] = {}
        self.surface = False  # X is a surface-family role: stepping it is a big change, so on-X is listed first
        self.source: Dict[str, Dict[str, str]] = {}  # mode -> token name -> the token that holds its value (alias chain end)

    @property
    def failed(self) -> List[str]:
        return [m for m, v in (("light", self.light), ("dark", self.dark)) if v < self.need]

    def options(self, mode: str) -> List[Tuple[str, str, str, float]]:
        """The fixes for a failing mode, best first, as (token name, token to change, proposed value, ratio). Text on a
        filled control (on-X near white or black over X): X stepped (the text stays) first; when X is a surface, on-X
        first. The token to change is where the value lives (the end of an alias chain)."""
        out: List[Tuple[str, str, str, float]] = []
        src = self.source.get(mode, {})
        bg_fix, fg_fix = self.fix_bg.get(mode), self.fix.get(mode)
        if bg_fix:
            out.append((self.bg, src.get(self.bg, self.bg_path), bg_fix[0], bg_fix[1]))
        if fg_fix:
            out.append((self.fg, src.get(self.fg, self.fg_path), fg_fix[0], fg_fix[1]))
        if bg_fix and fg_fix and self.surface:
            out.reverse()
        return out

    def _step(self, opt: Tuple[str, str, str, float], mode: str) -> str:
        name, path, value, ratio = opt
        own = self.bg_path if name == self.bg else self.fg_path
        text = f"step {name} to {value} ({ratio:.2f}:1"
        if name == self.bg and self.fix_bg.get(mode):
            text += f", {self.fg} stays {self.hex[mode][0]}"
        text += ")"
        if path != own:
            text += f" (it is an alias: change it at the source token {path})"
        return text

    def fix_text(self, mode: str, short: bool = False) -> str:
        """The failing mode's fixes in words (no trailing 'with /plumb:update'): one nearest value, or both options.
        `short` leaves the token name out of the single-value form (the contrast block names the pair already)."""
        opts = self.options(mode)
        if len(opts) == 2:
            return f"two options in {mode} mode: (1) {self._step(opts[0], mode)}; (2) {self._step(opts[1], mode)}"
        if opts:
            name, path, value, ratio = opts[0]
            own = self.bg_path if name == self.bg else self.fg_path
            alias = f" (it is an alias: change it at the source token {path})" if path != own else ""
            head = "nearest passing" if short and name == self.fg else f"nearest passing {name} in {mode} mode:"
            return f"{head} {value} ({ratio:.2f}:1){alias}"
        return ""


def _contrast_settings(doc: dict) -> dict:
    cfg = P.plumb_settings(doc)["contrast"]
    where = "$extensions.plumb.contrast"
    for key in ("surfaces", "ui", "extra_pairs"):
        if key in cfg and not isinstance(cfg[key], list):
            raise _err(f"{where}.{key} must be a list", f"write it as a list, e.g. {where}.{key}: []")
    for key in ("surfaces", "ui"):
        if not all(isinstance(x, str) for x in cfg.get(key, [])):
            raise _err(f"{where}.{key} must list token names as strings", 'write it like ["surface", "sunk"]')
    return cfg


def _blend(fg: str, alpha: float, bg: str) -> str:
    if alpha >= 1:
        return fg
    mix = [round(int(fg[i:i + 2], 16) * alpha + int(bg[i:i + 2], 16) * (1 - alpha)) for i in (1, 3, 5)]
    return "#" + "".join(f"{c:02x}" for c in mix)


def _oklch(hexv: str) -> Tuple[float, float, float]:
    """(L, C, hue in degrees) in OKLCH of an sRGB colour."""
    r, g, b = (P._linear(c) for c in P._rgb(hexv))
    l_ = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m_ = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s_ = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    lightness = 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_
    a = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_
    b2 = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_
    return lightness, math.hypot(a, b2), math.degrees(math.atan2(b2, a)) % 360


def _oklch_rgb(lightness: float, chroma: float, hue: float) -> Tuple[float, float, float]:
    a, b = chroma * math.cos(math.radians(hue)), chroma * math.sin(math.radians(hue))
    l_, m_, s_ = ((lightness + k) ** 3 for k in (0.3963377774 * a + 0.2158037573 * b,
                                                 -0.1055613458 * a - 0.0638541728 * b,
                                                 -0.0894841775 * a - 1.2914855480 * b))
    return (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
            -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
            -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)


def _oklch_to_hex(lightness: float, chroma: float, hue: float) -> str:
    """sRGB hex of an OKLCH colour; when it is outside sRGB the chroma is reduced (hue and lightness kept), never the
    channels clipped, so the hue stays within about a degree."""
    def inside(c: float) -> bool:
        return all(-0.0005 <= v <= 1.0005 for v in _oklch_rgb(lightness, c, hue))
    if not inside(chroma):
        lo, hi = 0.0, chroma
        for _ in range(24):
            mid = (lo + hi) / 2
            lo, hi = (mid, hi) if inside(mid) else (lo, mid)
        chroma = lo

    def enc(c: float) -> int:
        c = min(1.0, max(0.0, c))
        return round(255 * (12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055))

    return "#" + "".join(f"{enc(c):02x}" for c in _oklch_rgb(lightness, chroma, hue))


OKLCH_STEP = 0.002  # lightness step of the walk (about half a CIE L* point)


def _walk_lightness(fg: str, bg: str, need: float, lighten: bool) -> Optional[Tuple[str, float]]:
    lightness, chroma, hue = _oklch(fg)
    step = OKLCH_STEP if lighten else -OKLCH_STEP
    while (lightness < 1) if lighten else (lightness > 0):
        lightness = min(1.0, max(0.0, lightness + step))
        cand = _oklch_to_hex(lightness, chroma, hue)
        ratio = P.contrast(cand, bg)
        if ratio >= need:
            return cand, ratio
    return None


def nearest_passing(fg: str, bg: str, need: float, lighten: bool) -> Optional[Tuple[str, float]]:
    """The fg colour moved in small OKLCH lightness steps (hue kept; chroma reduced when the colour leaves sRGB) until it reaches `need` on bg: lighter when `lighten`, else
    darker; when that direction cannot reach it (white text on a light fill), the other direction is tried."""
    return _walk_lightness(fg, bg, need, lighten) or _walk_lightness(fg, bg, need, not lighten)


# The audit's contrast-headroom suggestion flags a pair that passes by less than HEADROOM; every value Plumb proposes
# aims at the minimum plus FIX_SPARE, so the same audit never flags a value Plumb proposed.
HEADROOM = 0.3
FIX_SPARE = 0.5


def proposed_value(fg: str, bg: str, need: float, lighten: bool) -> Optional[Tuple[str, float]]:
    """The value Plumb proposes for a foreground: the nearest that passes `need` with FIX_SPARE to spare; when this hue
    cannot get that far, with HEADROOM to spare; failing that, the nearest that passes at all."""
    for target in (need + FIX_SPARE, need + HEADROOM, need):
        found = nearest_passing(fg, bg, min(target, 21.0), lighten)
        if found:
            return found
    return None


# Text on a filled control is "white or black" when its colour is near-neutral and near an end of the lightness range
# (stock shadcn's primary-foreground is oklch(0.985 0 0), not #ffffff): OKLCH chroma at most NEUTRAL_CHROMA and WCAG
# relative luminance at least NEAR_WHITE_LUMINANCE (near white) or at most NEAR_BLACK_LUMINANCE (near black).
NEUTRAL_CHROMA = 0.02
NEAR_WHITE_LUMINANCE = 0.85
NEAR_BLACK_LUMINANCE = 0.03
# Roles that are surfaces besides SURFACE_NAMES, surface* and *-container (and the contrast.surfaces setting).
SURFACE_ROLES = frozenset(("raised", "card", "popover", "background", "page"))


def neutral_end(hexv: str) -> Optional[str]:
    """"white" or "black" for a near-neutral colour near either end of the lightness range, else None."""
    if _oklch(hexv)[1] > NEUTRAL_CHROMA:
        return None
    lum = P._luminance(hexv)
    return "white" if lum >= NEAR_WHITE_LUMINANCE else "black" if lum <= NEAR_BLACK_LUMINANCE else None


def is_surface_role(name: str, listed: "set" = frozenset()) -> bool:
    """X is a surface-family role (background, surface*, sunk, raised, card, popover, sidebar, *-container, or named in
    contrast.surfaces): stepping it changes every screen, so the on-X option is listed first for it."""
    return (name in listed or _is_surface_name(name) or name in SURFACE_ROLES or name.endswith("-raised")
            or name.endswith("-surface"))


def _source_path(doc: dict, path: str, mode: str) -> str:
    """The token that holds the value of `path` in a mode: follows {alias} references to the end of the chain."""
    seen = set()
    while path not in seen:
        seen.add(path)
        try:
            token, _rest, _ty = P._find(doc, path)
        except PlumbError:
            break
        ext = _token_ext(token)
        raw = ext["dark"] if mode == "dark" and "dark" in ext else token.get("$value")
        target = _alias_target(raw)
        if not target:
            break
        path = target
    return path


def contrast_pairs(doc: dict) -> List[Pair]:
    cfg = _contrast_settings(doc)
    keys: Dict[str, str] = {}  # name -> token path, colour tokens in file order
    for path, _tok, ttype in P.iter_tokens(doc):
        if ttype == "color":
            parts = P.path_parts(path)
            keys["-".join(parts[1:]) if parts[0] == "color" and len(parts) > 1 else "-".join(parts)] = path

    def known(name: object, where: str) -> str:
        text = str(name)
        if text in keys:
            return text
        if text.startswith("color."):
            return known(text[6:].replace(".", "-"), where)
        raise _err(f"{where}: unknown colour token {text!r}", "name a colour token from the tokens file, e.g. on-surface")

    listed = cfg.get("surfaces") or []
    surfaces = [known(n, "$extensions.plumb.contrast.surfaces") for n in listed]
    if not listed:
        surfaces = [k for k in keys if not _is_text_name(k) and _is_surface_name(k)]
    plain_surfaces = [k for k in surfaces if listed or not k.endswith("-container")]
    ui_names = [k for k in keys if k == "outline-input"] + [known(n, "$extensions.plumb.contrast.ui") for n in cfg.get("ui", [])]

    pairs: List[Pair] = []
    seen = set()

    def add(fg: str, bg: str, need: float) -> None:
        if fg != bg and (fg, bg) not in seen:
            seen.add((fg, bg))
            pairs.append(Pair(fg, bg, need))

    for k in keys:
        if k.startswith("on-") and k[3:] in keys:
            add(k, k[3:], NEED_TEXT)
    for k in keys:
        if k in ui_names:
            continue
        if k.startswith("on-"):
            base = k[3:]
            if _is_surface_name(base) and not base.endswith("-container"):
                for s_ in surfaces:
                    add(k, s_, NEED_TEXT)
        elif _is_text_name(k):
            for s_ in surfaces:
                add(k, s_, NEED_TEXT)
    for k in dict.fromkeys(ui_names):
        for s_ in plain_surfaces:
            add(k, s_, NEED_UI)

    extra = cfg.get("extra_pairs", [])
    kinds = {"text": NEED_TEXT, "large": NEED_UI, "ui": NEED_UI}
    for i, entry in enumerate(extra):
        where = f"$extensions.plumb.contrast.extra_pairs[{i}]"
        if isinstance(entry, list):
            if len(entry) != 3 or not all(isinstance(x, str) for x in entry) or entry[2] not in kinds:
                raise _err(f"{where} must be [fg, bg, kind] with kind text, large or ui",
                           'write it like ["on-primary-fill", "primary-fill", "text"]')
            add(known(entry[0], where), known(entry[1], where), kinds[entry[2]])
            continue
        if not isinstance(entry, dict) or not isinstance(entry.get("fg"), str) or not isinstance(entry.get("bg"), str):
            raise _err(f"{where} must be [fg, bg, kind] or an object with \"fg\" and \"bg\" token names",
                       'write it like ["primary", "background", "ui"] or {"fg": "primary", "bg": "background", "need": 3}')
        need = entry.get("need", NEED_TEXT)
        if isinstance(need, bool) or not isinstance(need, (int, float)) or not 1 <= need <= 21:
            raise _err(f"{where}.need must be a number from 1 to 21 (4.5 text, 3 large text or UI)", "write \"need\": 4.5 or \"need\": 3")
        add(known(entry["fg"], where), known(entry["bg"], where), float(need))
    return pairs


def _hex_in(doc: dict, path: str, mode: str) -> Tuple[str, float]:
    try:
        return P.parse_color(P.resolve(doc, path, mode))
    except PlumbError as exc:
        first, _, rest = str(exc).partition("\n")
        if first.startswith(f"error: {path}"):
            raise
        raise PlumbError(f"error: {path}: {first[len('error: '):]}\n{rest}") from None


def measure_pairs(doc: dict) -> List[Pair]:
    """contrast_pairs(doc) measured in light and dark: each Pair gets .light, .dark, .fix (proposed fg per
    failing mode), .fg_path / .bg_path (token paths) and .hex[mode] = (fg blended over bg, bg). audit.py uses this too."""
    pairs = contrast_pairs(doc)
    paths: Dict[str, str] = {}
    for path, _tok, ttype in P.iter_tokens(doc):
        if ttype == "color":
            parts = P.path_parts(path)
            paths["-".join(parts[1:]) if parts[0] == "color" and len(parts) > 1 else "-".join(parts)] = path
    listed = set(_contrast_settings(doc).get("surfaces") or [])
    for pair in pairs:
        pair.fg_path, pair.bg_path = paths[pair.fg], paths[pair.bg]
        pair.surface = is_surface_role(pair.bg, listed)
        for mode in ("light", "dark"):
            pair.source[mode] = {pair.fg: _source_path(doc, pair.fg_path, mode), pair.bg: _source_path(doc, pair.bg_path, mode)}
        for mode in ("light", "dark"):
            fg, fa = _hex_in(doc, paths[pair.fg], mode)
            bg, ba = _hex_in(doc, paths[pair.bg], mode)
            if ba < 1:
                raise _err(f"{pair.bg} is transparent, so {pair.fg} on {pair.bg} cannot be measured",
                           "use an opaque colour for the background in $extensions.plumb.contrast")
            fg = _blend(fg, fa, bg)
            pair.hex[mode] = (fg, bg)
            ratio = P.contrast(fg, bg)
            if mode == "light":
                pair.light = ratio
            else:
                pair.dark = ratio
            if ratio < pair.need:
                pair.fix[mode] = proposed_value(fg, bg, pair.need, lighten=(mode == "dark"))
                end = neutral_end(fg) if fa >= 1 and pair.fg == "on-" + pair.bg else None
                if end:  # text on a filled control: the fill moves away from the text colour, same hue
                    pair.fix_bg[mode] = proposed_value(bg, fg, pair.need, lighten=(end == "black"))
    return pairs


def contrast_block(doc: dict) -> str:
    """The generated text between the contrast markers (no trailing newline)."""
    pairs = measure_pairs(doc)
    failing = [p for p in pairs if p.failed]
    L = [
        "Generated by `build-tokens.py --contrast` from the tokens file (WCAG 2.x relative luminance). Do not edit this block:",
        "change the tokens, then run the command again. Text needs 4.5:1; large text and UI boundaries need 3:1.",
        "",
        f"{len(pairs)} pairs checked, {len(failing)} failing.",
        "",
        "| Pair | Light | Dark | Need | Result |",
        "|---|---:|---:|---:|---|",
    ]
    for p in pairs:
        result = "pass" if not p.failed else "fail (" + ", ".join(p.failed) + ")"
        L.append(f"| {p.fg} on {p.bg} | {p.light:.2f} | {p.dark:.2f} | {num(p.need)} | {result} |")
    if failing:
        L += ["", "Nearest passing values with 0.5 to spare (the colour nudged in OKLCH lightness, hue kept: the text lighter in dark mode, darker in light mode; for text on a filled control, the fill is the first option, away from the text colour, unless the fill is a surface):", ""]
        for p in failing:
            for mode in p.failed:
                if p.options(mode):
                    L.append(f"- {p.fg} on {p.bg} ({mode}): " + p.fix_text(mode, short=True))
                else:
                    L.append(f"- {p.fg} on {p.bg} ({mode}): no value of this hue passes; change the background")
    return "\n".join(L)


def apply_contrast_block(text: str, block: str) -> Optional[str]:
    """`text` with the marked block replaced (its own line endings kept), or None when the markers are missing."""
    if text.count(CONTRAST_START) != 1 or text.count(CONTRAST_END) != 1:
        return None
    start = text.index(CONTRAST_START) + len(CONTRAST_START)
    end = text.index(CONTRAST_END)
    if end < start:
        return None
    nl = "\r\n" if "\r\n" in text else "\n"
    return text[:start] + nl + block.replace("\n", nl) + nl + text[end:]


def read_dark_doc(skill_dir: Path) -> Optional[str]:
    path = skill_dir / DARK_DOC_REL
    if not path.is_file():
        return None
    try:
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise _err(f"{path}: cannot read ({exc})", "save it as UTF-8") from None


def contrast_output(doc: dict, skill_dir: Path, required: bool) -> Optional[Tuple[Path, str]]:
    """(path, new text) for references/dark-mode.md; None when it is absent or unmarked and not required."""
    path = skill_dir / DARK_DOC_REL
    text = read_dark_doc(skill_dir)
    if text is None:
        if required:
            raise _err(f"{path} not found", f"copy references/dark-mode.md.tmpl from the Plumb plugin's assets/skill/ to {path}, then run --contrast again")
        return None
    new = apply_contrast_block(text, contrast_block(doc))
    if new is None:
        if required:
            raise _err(f"{path} has no {CONTRAST_START} ... {CONTRAST_END} markers",
                       f"add the two marker lines on their own lines where the table should go in {path}")
        print(f"note: the contrast block in {path.name} was not refreshed (no {CONTRAST_START} / {CONTRAST_END} markers); "
              f"add those two lines where the table should go, then run build-tokens.py --contrast", file=sys.stderr)
        return None
    return path, new


