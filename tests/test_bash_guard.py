def _rel(paths, base: Path):
    out = []
    for p in paths:
        try:
            out.append(str(Path(p).relative_to(base)).replace("\\", "/"))
        except ValueError:
            out.append(p)
    return out


def _effects(H, command: str, base: Path):
    return _rel(_targets(H, command, str(base)), base) + _rel(_removals(H, command, str(base)), base)


