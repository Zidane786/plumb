@pytest.fixture(scope="module")
def H():
    spec = importlib.util.spec_from_file_location("plumb_hooklib_bash_guard", HOOKS / "_hooklib.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["plumb_hooklib_bash_guard"] = mod
    spec.loader.exec_module(mod)
    return mod


def _rel(paths, base: Path):
    out = []
    for p in paths:
        try:
            out.append(str(Path(p).relative_to(base)).replace("\\", "/"))
        except ValueError:
            out.append(p)
    return out


def _effects(H, command: str, base: Path):
    return _rel(H.shell_targets(command, str(base)), base) + _rel(H.shell_removals(command, str(base)), base)


@pytest.mark.parametrize("form", WRITE_FORMS)
def test_every_write_form_names_its_target(H, tmp_path, form):
    for target in ("docs/design/screens.html", "web/src/app/globals.css"):  # two folder shapes
        assert target in _effects(H, form.format(t=target), tmp_path), (form, _effects(H, form.format(t=target),
                                                                                       tmp_path))


@pytest.mark.parametrize("command", READS)
def test_reads_name_no_guarded_target(H, tmp_path, command):
    found = _effects(H, command, tmp_path)
    assert not any(t in (OWN, GEN, MAP) for t in found), found


