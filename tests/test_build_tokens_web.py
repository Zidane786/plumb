def test_outputs_function(project: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.syspath_prepend(str(SCRIPTS))
    import importlib.util

    import _plumb as P

    spec = importlib.util.spec_from_file_location("build_tokens_under_test", SCRIPTS / "build-tokens.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    doc = P.load_tokens(tokens_path(project))
    out = mod.outputs(doc, skill(project))
    assert all(isinstance(k, Path) and k.is_absolute() for k in out)
    assert out[css_out(project).resolve()] == out[(project / "app/globals.css").resolve()]


