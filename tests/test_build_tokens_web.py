"""build-tokens.py web outputs (tailwind v4, v3, css), copies and --check."""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SCRIPTS = REPO / "plugins/plumb/assets/skill/scripts"
WEB_TEMPLATES = REPO / "plugins/plumb/assets/skill/assets/platforms/web"
FIXTURE = REPO / "tests/fixtures/projects/web-v4"
SKILL_REL = ".claude/skills/demo-design-system"


@pytest.fixture()
def project(tmp_path: Path) -> Path:
    dest = tmp_path / "proj"
    shutil.copytree(FIXTURE, dest)
    scripts = dest / SKILL_REL / "scripts"
    for name in ("_plumb.py", "build-tokens.py"):
        shutil.copy(SCRIPTS / name, scripts / name)
    return dest


def skill(p: Path) -> Path:
    return p / SKILL_REL


def run(p: Path, *args: str, script: Path | None = None):
    script = script or skill(p) / "scripts/build-tokens.py"
    return subprocess.run(
        [sys.executable, str(script), *args], cwd=str(p), capture_output=True, text=True, encoding="utf-8"
    )


def tokens_path(p: Path) -> Path:
    return skill(p) / "assets/tokens/demo.tokens.json"


def edit_tokens(p: Path, fn) -> None:
    doc = json.loads(tokens_path(p).read_text(encoding="utf-8"))
    fn(doc)
    with open(tokens_path(p), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(doc, indent=2))


def set_mode(p: Path, mode: str) -> None:
    edit_tokens(p, lambda d: d["$extensions"]["plumb"]["web"].__setitem__("styling", mode))
    shutil.copy(WEB_TEMPLATES / f"tokens.css.template.{mode}", skill(p) / "assets/platforms/web/tokens.css.template")


def css_out(p: Path) -> Path:
    return skill(p) / "assets/platforms/web/tokens.css"


def test_fixture_template_is_the_shipped_v4_template() -> None:
    fx = FIXTURE / SKILL_REL / "assets/platforms/web/tokens.css.template"
    assert fx.read_bytes() == (WEB_TEMPLATES / "tokens.css.template.tailwind-v4").read_bytes()


def test_v4_output(project: Path) -> None:
    r = run(project)
    assert r.returncode == 0, r.stderr
    css = css_out(project).read_text(encoding="utf-8")
    assert css.startswith(
        "/* GENERATED by .claude/skills/demo-design-system/scripts/build-tokens.py from "
        ".claude/skills/demo-design-system/assets/tokens/demo.tokens.json. "
        "Do not edit: edit the tokens JSON, then run build-tokens.py. */"
    )
    assert "@theme static {" in css
    assert "--color-primary: #14857f;" in css
    assert "--color-link: var(--color-primary);" in css
    assert "--color-scrim: rgb(15 18 23 / 0.80);" in css
    assert '--font-sans: Inter, system-ui, "Segoe UI", sans-serif;' in css
    assert "--text-sm: 16px;" in css and "--text-sm--line-height: 24px;" in css
    assert "--text-sm--font-weight: 400;" in css
    assert "--radius-lg: 10px;" in css  # DTCG object dimension
    assert "--duration-mid: 180ms;" in css and "--ease-out: cubic-bezier(0.2, 0.8, 0.2, 1);" in css
    assert "--shadow-card: 0px 1px 3px rgb(15 18 23 / 0.08);" in css
    dark = css.split(".dark {", 1)[1].split("}", 1)[0]
    assert "--color-primary: #4fb3c4;" in dark and "--color-background: #0f1217;" in dark
    assert "--color-on-primary" not in dark and "--color-link" not in dark  # no dark value of their own
    assert "--shadow-card: 0px 1px 3px rgb(0 0 0 / 0.40);" in dark
    md = css.split("@media (width >= 48rem)", 1)[1].split("}", 1)[0]
    assert "--text-sm: 14px;" in md and "--text-sm--line-height: 20px;" in md
    assert "@media (prefers-reduced-motion: reduce)" in css
    assert "{{" not in css
    low = css.lower()
    assert "keel" not in low and "caredesk" not in low


def test_v3_output(project: Path) -> None:
    set_mode(project, "tailwind-v3")
    r = run(project)
    assert r.returncode == 0, r.stderr
    css = css_out(project).read_text(encoding="utf-8")
    assert "@theme" not in css and "@import" not in css
    assert ":root {" in css and "--color-primary: #14857f;" in css and ".dark {" in css
    assert "prefers-reduced-motion" in css
    js_path = skill(project) / "assets/platforms/web/tailwind.tokens.js"
    js = js_path.read_text(encoding="utf-8")
    assert js.startswith("/* GENERATED by .claude/skills/demo-design-system/scripts/build-tokens.py")
    assert '"primary": "var(--color-primary)"' in js
    assert js.rstrip().endswith("};")
    assert "module.exports = {" in js
    node = shutil.which("node")
    if node:
        out = subprocess.run(
            [node, "-e", f"const t=require({json.dumps(str(js_path))});console.log(JSON.stringify(t))"],
            capture_output=True, text=True, encoding="utf-8",
        )
        assert out.returncode == 0, out.stderr
        data = json.loads(out.stdout)
        assert data["colors"]["primary"] == "var(--color-primary)"
        assert data["fontSize"]["sm"][0] == "var(--text-sm)"
    else:
        assert re.search(r'"fontSize": \{', js)


