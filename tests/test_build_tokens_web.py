# ---------------------------------------------------------------- dark mode reachable, reduced motion as recorded


def dark_rules(css: str) -> dict:
    found = {}
    for name, opener in (("media", "@media (prefers-color-scheme: dark) {\n  :root:not(.light) {"),
                         ("class", "\n.dark {"), ("light", "\n.light {")):
        if opener in css:
            found[name] = css.split(opener, 1)[1].split("}", 1)[0]
    return found


@pytest.mark.parametrize("mode", ["tailwind-v4", "tailwind-v3", "css"])
def test_dark_values_follow_the_system_and_the_class_by_default(project: Path, mode: str) -> None:
    set_mode(project, mode)
    assert run(project).returncode == 0
    rules = dark_rules(css_out(project).read_text(encoding="utf-8"))
    assert set(rules) == {"media", "class", "light"}
    for name in ("media", "class"):
        assert "--color-primary: #4fb3c4;" in rules[name] and "color-scheme: dark;" in rules[name]
    # .light puts back the light value of every token that changes in dark, and only those
