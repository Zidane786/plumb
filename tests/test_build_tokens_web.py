def assert_refusal(r, *needles: str) -> None:
    assert r.returncode == 2, r.stdout + r.stderr
    text = r.stderr
    assert text.startswith("error:") and ("\nfix:" in text or "ask the user:" in text), text
    assert "Traceback" not in text
    for n in needles:
        assert n in text, text


