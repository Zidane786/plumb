def test_project_root_ruling_plumb_md_wins_then_flag_then_parents(project: Path, tmp_path: Path) -> None:
    # PLUMB.md found upward: copies relative to it
    assert run(project).returncode == 0
    assert (project / "app/globals.css").read_text(encoding="utf-8").startswith("/* GENERATED")
    # No PLUMB.md: --project PATH is used
    (project / "PLUMB.md").unlink()
    (project / "app/globals.css").unlink()
    alt = tmp_path / "alt"
    alt.mkdir()
    r = run(project, "--project", str(alt))
    assert r.returncode == 0, r.stderr
    assert (alt / "app/globals.css").exists() and not (project / "app/globals.css").exists()
    # Neither: skill_dir.parents[2] (= the project here)
    r = run(project)
    assert r.returncode == 0, r.stderr
    assert (project / "app/globals.css").exists()


