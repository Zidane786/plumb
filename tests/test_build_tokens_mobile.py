"""build-tokens.py mobile outputs: SwiftUI and Jetpack Compose themes from the same tokens JSON."""

from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SCRIPTS = REPO / "plugins/plumb/assets/skill/scripts"
FIXTURE = REPO / "tests/fixtures/projects/web-v4"
SKILL_REL = ".claude/skills/demo-design-system"
MOBILE = "assets/platforms/mobile"


def load_module():
    spec = importlib.util.spec_from_file_location("build_tokens_under_test", SCRIPTS / "build-tokens.py")
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(SCRIPTS))
    spec.loader.exec_module(mod)
    return mod


BT = load_module()


def write(path: Path, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def make_project(tmp_path: Path, platforms, project: str = "demo") -> Path:
    dest = tmp_path / "proj"
    shutil.copytree(FIXTURE, dest)
    scripts = dest / SKILL_REL / "scripts"
    for name in ("_plumb.py", "build-tokens.py"):
        shutil.copy(SCRIPTS / name, scripts / name)
    tokens = dest / SKILL_REL / "assets/tokens/demo.tokens.json"
    doc = json.loads(tokens.read_text(encoding="utf-8"))
    doc["$extensions"]["plumb"]["platforms"] = platforms
    doc["$extensions"]["plumb"]["project"] = project
    write(tokens, json.dumps(doc, indent=2))
    return dest


@pytest.fixture()
def project(tmp_path: Path) -> Path:
    return make_project(tmp_path, ["web", "ios", "android"], "demo")


def skill(p: Path) -> Path:
    return p / SKILL_REL


def run(p: Path, *args: str):
    return subprocess.run(
        [sys.executable, str(skill(p) / "scripts/build-tokens.py"), *args],
        cwd=str(p), capture_output=True, text=True, encoding="utf-8",
    )


def swift(p: Path, name: str = "Demo") -> str:
    return (skill(p) / MOBILE / "ios" / f"{name}Theme.swift").read_text(encoding="utf-8")


def kotlin(p: Path, name: str = "Demo") -> str:
    return (skill(p) / MOBILE / "android" / f"{name}Theme.kt").read_text(encoding="utf-8")


def test_pascal_case_strips_diacritics_and_punctuation() -> None:
    assert BT.pascal("café-ünïcode") == "CafeUnicode"
    assert BT.pascal("Café Ünïcode") == "CafeUnicode"
    assert BT.pascal("my_cool app") == "MyCoolApp"
    assert BT.pascal("---") == ""


def test_swift_output(project: Path) -> None:
    r = run(project)
    assert r.returncode == 0, r.stderr
    text = swift(project)
    assert text.startswith(
        "// GENERATED by .claude/skills/demo-design-system/scripts/build-tokens.py from "
        ".claude/skills/demo-design-system/assets/tokens/demo.tokens.json. "
        "Do not edit: edit the tokens JSON, then run build-tokens.py.\n"
    )
    assert "public enum DemoColor {" in text
    # a light/dark pair for every colour token (aliases resolved, alpha kept, no dark override falls back to light)
    assert "public static let background = Color(demoLight: 0xFFFFFF, dark: 0x0F1217)" in text
    assert "public static let primary = Color(demoLight: 0x14857F, dark: 0x4FB3C4)" in text
    assert "public static let onPrimary = Color(demoLight: 0xFFFFFF, dark: 0xFFFFFF)" in text
    assert "public static let link = Color(demoLight: 0x14857F, dark: 0x4FB3C4)" in text
    assert "public static let scrim = Color(demoLight: 0x0F1217, lightAlpha: 0.8, dark: 0x000000, darkAlpha: 0.8)" in text
    # type scale: 16px/24px -> 1.5, 12px/16px -> 1.3333, Inter is a named family, system fonts are not
    assert "public enum DemoType {" in text
    assert "public static let sm = DemoTextStyle(size: 16, weight: .regular, lineHeight: 1.5, tracking: 0," in text
    assert "public static let xs = DemoTextStyle(size: 12, weight: .regular, lineHeight: 1.3333, tracking: 0," in text
    assert '.custom("Inter"' in text
    assert "public enum DemoRadius {" in text
    assert "public static let md: CGFloat = 6" in text
    assert "public static let lg: CGFloat = 10" in text
    assert "public static let s2: CGFloat = 8" in text
    assert "public enum DemoMotion {" in text
    assert "public static let fast: Double = 0.15  // seconds" in text
    assert "public static let mid: Double = 0.18  // seconds" in text
    assert "easeOut(_ duration: Double) -> Animation { .timingCurve(0.2, 0.8, 0.2, 1, duration: duration) }" in text
    assert "public static let card = DemoShadow(x: 0, y: 1, radius: 1.5," in text
    assert "Icon" not in text  # no icon map in this project: the section is left out
    assert "Keel" not in text and "keel" not in text
    assert "\r" not in text and text.endswith("\n")


def test_kotlin_output(project: Path) -> None:
    assert run(project).returncode == 0
    text = kotlin(project)
    assert text.startswith("// GENERATED by .claude/skills/demo-design-system/scripts/build-tokens.py from ")
    assert "package app.demo.designsystem" in text
    assert "data class DemoColors(" in text
    assert "val DemoLightColors = DemoColors(" in text and "val DemoDarkColors = DemoColors(" in text
    assert "background = Color(0xFFFFFFFF)," in text
    assert "scrim = Color(0xCC0F1217)," in text  # alpha first (ARGB)
    assert "= lightColorScheme(" in text and "= darkColorScheme(" in text
    assert "primary = DemoLightColors.primary," in text
    assert "onBackground = DemoLightColors.onSurface," in text
    assert "surfaceVariant = DemoLightColors.background," in text  # no sunk/column/surface token: derived, never Material purple
    assert "fun demoTypography(fontFamily: FontFamily = FontFamily.Default): Typography {" in text
    assert "val sm = TextStyle(fontFamily = fontFamily, fontSize = 16.sp, fontWeight = FontWeight.W400, lineHeight = 24.sp" in text
    assert "return Typography(" in text
    assert "val DemoShapes = Shapes(" in text and "RoundedCornerShape(6.dp)" in text and "RoundedCornerShape(10.dp)" in text
    assert "object DemoRadius {" in text and "val lg = 10.dp" in text
    assert "const val fastMillis = 150" in text and "const val midMillis = 180" in text
    assert "val EaseOut = CubicBezierEasing(0.2f, 0.8f, 0.2f, 1f)" in text
    assert "fun DemoTheme(" in text and "object DemoTheme {" in text
    assert "Keel" not in text and "keel" not in text


def test_idempotent(project: Path) -> None:
    assert run(project).returncode == 0
    first = {p: p.read_bytes() for p in (skill(project) / MOBILE).rglob("*") if p.is_file()}
    assert len(first) == 2
    r = run(project)
    assert r.returncode == 0 and "wrote" not in r.stdout
    assert first == {p: p.read_bytes() for p in (skill(project) / MOBILE).rglob("*") if p.is_file()}
    assert run(project, "--check").returncode == 0


def test_only_listed_platforms_are_written(tmp_path: Path) -> None:
    p = make_project(tmp_path, ["web", "ios"])
    assert run(p).returncode == 0
    assert (skill(p) / MOBILE / "ios/DemoTheme.swift").is_file()
    assert not (skill(p) / MOBILE / "android").exists()
    p2 = make_project(tmp_path / "b", ["web"])
    assert run(p2).returncode == 0
    assert not (skill(p2) / MOBILE).exists()


def test_check_catches_stale_swift(project: Path) -> None:
    assert run(project).returncode == 0
    path = skill(project) / MOBILE / "ios/DemoTheme.swift"
    write(path, path.read_text(encoding="utf-8") + "// hand edit\n")
    r = run(project, "--check")
    assert r.returncode == 1
    assert "stale: .claude/skills/demo-design-system/assets/platforms/mobile/ios/DemoTheme.swift" in r.stdout
    assert "fix: python3 .claude/skills/demo-design-system/scripts/build-tokens.py" in r.stdout


def test_check_reports_missing_mobile_files(project: Path) -> None:
    r = run(project, "--check")
    assert r.returncode == 1
    assert "DemoTheme.swift" in r.stdout and "DemoTheme.kt" in r.stdout


