def test_missing_project_name_is_refused(tmp_path: Path) -> None:
    p = make_project(tmp_path, ["ios"], "---")
    r = run(p)
    assert r.returncode == 2
    assert r.stderr.startswith("error: ") and "fix: set $extensions.plumb.project" in r.stderr
    assert "Traceback" not in r.stderr


def test_icon_map_is_included_when_present(project: Path) -> None:
    icons = skill(project) / "assets/icons"
    icons.mkdir(parents=True)
    write(icons / "icon-map.json", json.dumps({"icons": [{"concept": "home", "sfSymbol": "house", "materialSymbol": "home"},
                              {"concept": "class", "sfSymbol": "book", "materialSymbol": "menu_book"}]}))
    assert run(project).returncode == 0
    assert 'case home = "house"' in swift(project)
    assert 'case `class` = "book"' in swift(project)
    assert 'home("home"),' in kotlin(project)


def test_bad_icon_map_is_refused(project: Path) -> None:
    icons = skill(project) / "assets/icons"
    icons.mkdir(parents=True)
    write(icons / "icon-map.json", '{"icons": [{"concept": "home"}]}')
    r = run(project)
    assert r.returncode == 2 and "missing sfSymbol" in r.stderr and "fix:" in r.stderr
