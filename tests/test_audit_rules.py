def test_block_override_says_whether_it_replaces_a_token_or_adds_a_name() -> None:
    text = _BLOCK + ("@theme inline {\n  --color-background: var(--background);\n  --color-foreground: var(--fg);\n"
                     "  --font-sans: var(--font-geist-sans);\n  --color-*: initial;\n}\n")
    found = {f.match: f for f in A.audit_text("app/globals.css", text, DOC, SETTINGS)}
    assert set(found) == {"--color-background", "--color-foreground", "--font-sans", "--color-*"}
    assert all(f.rule == "block-override" for f in found.values())
    assert "replaces the token color.background" in found["--color-background"].message
    assert "replaces the token font.sans" in found["--font-sans"].message
    fg = found["--color-foreground"].message
    assert "adds --color-foreground to the design tokens' --color-* namespace" in fg and "replaces" not in fg
    assert "every --color-* token" in found["--color-*"].message
    for f in found.values():
        assert "/plumb:update" in f.fix and "build-tokens.py --overrides" in f.fix


